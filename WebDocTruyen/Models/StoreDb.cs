using Npgsql;

namespace WebDocTruyen.Models
{
    /// <summary>Truy cập Postgres (Supabase) cho các "store" tĩnh; tự tạo bảng khi khởi động.</summary>
    public static class StoreDb
    {
        public static string ConnectionString { get; private set; } = string.Empty;

        public static NpgsqlConnection Open()
        {
            var c = new NpgsqlConnection(ConnectionString);
            c.Open();
            return c;
        }

        public static void Init(string connectionString)
        {
            ConnectionString = connectionString;
            using var c = Open();
            using var cmd = new NpgsqlCommand(@"
CREATE TABLE IF NOT EXISTS ""QuocGia"" (
    ""MaQuocGia""  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ""TenQuocGia"" varchar(100) NOT NULL,
    ""MaIso""      varchar(10),
    ""MoTa""       varchar(500)
);
CREATE TABLE IF NOT EXISTS ""TruyenQuocGia"" (
    ""MaTruyen"" integer PRIMARY KEY REFERENCES ""Truyen""(""MaTruyen"") ON DELETE CASCADE,
    ""QuocGia""  varchar(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS ""BinhLuanLike"" (
    ""MaBinhLuan""  integer NOT NULL REFERENCES ""BinhLuanChuong""(""MaBinhLuan"") ON DELETE CASCADE,
    ""MaNguoiDung"" integer NOT NULL REFERENCES ""NguoiDung""(""MaNguoiDung"") ON DELETE CASCADE,
    ""NgayTao""     timestamp NOT NULL DEFAULT now(),
    PRIMARY KEY (""MaBinhLuan"", ""MaNguoiDung"")
);
CREATE TABLE IF NOT EXISTS ""ThichTruyen"" (
    ""MaNguoiDung"" integer NOT NULL REFERENCES ""NguoiDung""(""MaNguoiDung"") ON DELETE CASCADE,
    ""MaTruyen""    integer NOT NULL REFERENCES ""Truyen""(""MaTruyen"") ON DELETE CASCADE,
    ""NgayTao""     timestamp NOT NULL DEFAULT now(),
    PRIMARY KEY (""MaNguoiDung"", ""MaTruyen"")
);
INSERT INTO ""QuocGia"" (""MaQuocGia"", ""TenQuocGia"", ""MaIso"", ""MoTa"") OVERRIDING SYSTEM VALUE
SELECT * FROM (VALUES
 (1, 'Trung Quốc', 'CN', 'Truyện Manhua, Tiên hiệp, Huyền huyễn'),
 (2, 'Việt Nam',   'VN', 'Tác phẩm tác giả Việt Nam sáng tác'),
 (3, 'Hàn Quốc',   'KR', 'Truyện Manhwa, Thợ săn, Hầm ngục'),
 (4, 'Nhật Bản',   'JP', 'Truyện Manga, Light Novel, Isekai'),
 (5, 'Mỹ',         'US', 'Comic, Siêu anh hùng, Viễn tưởng Âu Mỹ')
) v(a,b,c,d) WHERE NOT EXISTS (SELECT 1 FROM ""QuocGia"");
SELECT setval(pg_get_serial_sequence('""QuocGia""','MaQuocGia'), COALESCE((SELECT MAX(""MaQuocGia"") FROM ""QuocGia""),0)+1, false);", c);
            cmd.ExecuteNonQuery();
        }
    }
}
